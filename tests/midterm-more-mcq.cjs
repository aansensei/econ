const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),core=require(path.join(root,'midterm.js'));
const bankCode=fs.readFileSync(path.join(root,'midterm-data.js'),'utf8');
const main=fs.readFileSync(path.join(root,'midterm.js'),'utf8');
const storage=new Map();
function load(hash='#home'){
 const nodes=new Map();
 function node(id){if(!nodes.has(id))nodes.set(id,{id,innerHTML:'',hidden:false,handlers:{},classList:{toggle(){}},addEventListener(name,fn){this.handlers[name]=fn;},querySelectorAll(){return [];}});return nodes.get(id);}
 const ctx=vm.createContext({window:{addEventListener(){},scrollTo(){}},document:{getElementById:node,querySelectorAll(){return [];}},location:{hash},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},console,setInterval(){return 1;},clearInterval(){}});
 vm.runInContext(bankCode,ctx);
 const last=main.lastIndexOf('}');
 vm.runInContext(main.slice(0,last)+'globalThis.testAPI={selectQuestions,record,progress,card};'+main.slice(last),ctx);
 return {api:ctx.testAPI,bank:ctx.window.MIDTERM_DATA.bank,node};
}
let model=load();
const more=model.bank.filter(q=>q.category==='more');
assert.equal(more.length,14);
assert(model.node('app').innerHTML.includes('14 cards | 0/14 objective correct'));
for(const q of more){
 assert.equal(q.type,'mcq',q.id);
 assert.equal(q.opts.length,4,q.id);
 assert.equal(new Set(q.opts).size,4,q.id);
 assert.equal(q.adaptedFromOpen,true,q.id);
 assert.equal(q.wordingVerified,false,q.id);
 assert.equal(q.verified,'derived',q.id);
 assert.equal(q.sim,false,q.id);
 assert(q.originalStem.length>30,q.id);
 assert(q.note.includes('Đề tự luận gốc của cô'),q.id);
 for(let choice=0;choice<4;choice++)assert.equal(core.grade(q,choice),choice===q.ans,q.id);
 const rendered=model.api.card(q,0,'review',null,null);
 assert.equal((rendered.match(/type="radio"/g)||[]).length,4,q.id);
 assert(!rendered.includes('textarea'),q.id);
 assert(!rendered.includes('Self-check'),q.id);
 assert(rendered.includes('MCQ chuyển thể từ bài gốc'),q.id);
 assert(rendered.includes('Official answer video'),q.id);
 assert(rendered.includes('Check answer'),q.id);
 const feedback=model.api.card(q,0,'review',q.ans,{answer:q.ans,ok:true});
 assert(feedback.includes('✓ Đúng'),q.id);
 assert(feedback.includes('<summary>Đề tự luận gốc của cô</summary>'),q.id);
 assert(!feedback.includes('&lt;strong&gt;'),q.id);
}
const byId=new Map(more.map(q=>[q.id,q]));
assert.equal(byId.get('m1_more23_1').opts[byId.get('m1_more23_1').ans],'0.6 percent');
const requiredGrowth=(0.10/0.09-1)*100;
assert(Math.abs(requiredGrowth-11.111111)<0.00001);
assert(byId.get('m1_more23_2').opts[byId.get('m1_more23_2').ans].includes('11.11 percent'));
assert.equal(byId.get('m1_more4_3').opts[byId.get('m1_more4_3').ans],'N = 16a/(a+b)');
const N=16*0.5/(0.5+0.25),C=10*N;
assert.equal(byId.get('m1_more4_4').opts[byId.get('m1_more4_4').ans],`C = ${C.toFixed(2)}; N = ${N.toFixed(2)}`);
for(const [chapter,count] of [[2,2],[3,2],[4,6],[5,6]])assert.equal(core.filterQuestions(more,{chapter:String(chapter)}).length,count);
model.node('app').handlers.click({target:{closest:()=>({dataset:{browse:'more'}})}});
assert.equal(model.api.selectQuestions().length,14);
assert(model.api.selectQuestions().every(q=>q.type==='mcq'));
assert(model.node('app').innerHTML.includes('0/14 objective questions correct'));
assert(!model.node('app').innerHTML.includes('Xem rubric'));
const q=more[0];
model.api.record(q,false,(q.ans+1)%4);
model=load('#mistakes');
assert(model.api.selectQuestions().some(x=>x.id===q.id));
for(const x of more)model.api.record(x,true,x.ans);
assert.equal(model.api.progress(more).correct,14);
model=load('#home');
assert(model.node('app').innerHTML.includes('14 cards | 14/14 objective correct'));
for(let i=0;i<25;i++)assert(core.simulation(model.bank).every(x=>!byId.has(x.id)));
storage.clear();
const essay={answer:'My saved explanation',result:{answer:'My saved explanation',ok:null,self:1}};
const answered={answer:q.ans,result:{answer:q.ans,ok:true}};
storage.set('econ302_midterm_review',JSON.stringify({[q.id]:essay,m1_more4_3:answered,m1_f19_25:{answer:1,result:{answer:1,ok:true}}}));
model=load();
const review=JSON.parse(storage.get('econ302_midterm_review'));
assert(!review[q.id]);
assert.deepEqual(review.m1_more4_3,answered);
assert.equal(review.m1_f19_25.answer,1);
assert.deepEqual(JSON.parse(storage.get('econ302_more_open_archive'))[q.id],essay);
console.log('PASS: 14 adapted MCQs, calculated answers, grading, chapter filters, objective progress, Mistakes, source links and saved essay migration.');
